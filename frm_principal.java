    private void buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarActionPerformed
      String textoBuscar = JOptionPane.showInputDialog(
            this,
            "Ingrese el texto a buscar");

    if (textoBuscar == null || textoBuscar.isEmpty()) {
        return;
    }

    String contenido = area_txt.getText();

    int posicion = contenido.toLowerCase()
            .indexOf(textoBuscar.toLowerCase());

    if (posicion >= 0) {

        area_txt.requestFocus();

        area_txt.select(
                posicion,
                posicion + textoBuscar.length());

        JOptionPane.showMessageDialog(
                this,
                "Texto encontrado");

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Texto no encontrado");

    }
    }//GEN-LAST:event_buscarActionPerformed

    private void reemplazarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_reemplazarActionPerformed
         String buscar = JOptionPane.showInputDialog(
            this,
            "Texto a buscar:");

    if (buscar == null || buscar.isEmpty()) {
        return;
    }

    String reemplazo = JOptionPane.showInputDialog(
            this,
            "Nuevo texto:");

    if (reemplazo == null) {
        return;
    }

    String contenido = area_txt.getText();

    contenido = contenido.replace(buscar, reemplazo);

    area_txt.setText(contenido);

    }//GEN-LAST:event_reemplazarActionPerformed

