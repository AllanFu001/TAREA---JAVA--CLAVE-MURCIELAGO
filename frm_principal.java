    private void bt_procesarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bt_procesarActionPerformed
        String texto = area_txt.getText().trim();

    if (texto.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Ingrese un texto primero");
        return;
    }

    
    lbl_r_longitud.setText(String.valueOf(texto.length()));

   
    String[] palabras = texto.split("\\s+");

    lbl_r_palabras.setText(String.valueOf(palabras.length));

    
    lbl_r_primeraletra.setText(
            String.valueOf(texto.charAt(0)));

   
    lbl_r_ultimaletra.setText(
            String.valueOf(texto.charAt(texto.length() - 1)));

    
    int centro = texto.length() / 2;

    lbl_r_centralletra.setText(
            String.valueOf(texto.charAt(centro)));

    
    lbl_r_primerapalabra.setText(
            palabras[0]);

    
    lbl_r_palabracentral.setText(
            palabras[palabras.length / 2]);

    
    lbl_r_ultimapalabra.setText(
            palabras[palabras.length - 1]);

    

    int a = 0;
    int e = 0;
    int i = 0;
    int o = 0;
    int u = 0;

    for (char c : texto.toCharArray()) {

        switch (Character.toLowerCase(c)) {

            case 'a':
            case 'á':
                a++;
                break;

            case 'e':
            case 'é':
                e++;
                break;

            case 'i':
            case 'í':
                i++;
                break;

            case 'o':
            case 'ó':
                o++;
                break;

            case 'u':
            case 'ú':
                u++;
                break;

        }

    }

    lbl_r_a.setText(String.valueOf(a));
    lbl_r_e.setText(String.valueOf(e));
    lbl_r_i.setText(String.valueOf(i));
    lbl_r_o.setText(String.valueOf(o));
    lbl_r_u.setText(String.valueOf(u));

    

    int pares = 0;
    int impares = 0;

    for (String palabra : palabras) {

        if (palabra.length() % 2 == 0) {

            pares++;

        } else {

            impares++;

        }

    }

    lbl_r_par.setText(String.valueOf(pares));
    lbl_r_impar.setText(String.valueOf(impares));
area_traduccion.setText(
        traducirMurcielago(texto));
    }//GEN-LAST:event_bt_procesarActionPerformed

